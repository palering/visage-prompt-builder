export function catalogChinese(value, module, field) {
  // A shared source word has different meanings in hair and cosmetics.
  const translated = (module === 'makeup' && field === 'coverage' ? {none:'无底妆',sheer:'轻透遮盖',medium:'中等遮盖',full:'高遮盖'}[value] : undefined) ?? CATALOG_ZH[value];
  if (translated === undefined) throw new Error(`Missing Chinese catalog translation: ${module}.${field}: ${value}`);
  return translated;
}
